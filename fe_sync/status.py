"""Human-readable local Moodle sync health, never exposing credentials."""
from __future__ import annotations

from datetime import datetime, timezone
from html import escape
import json
import os
from pathlib import Path
import tempfile

from .pages import MARKER, write_generated
from .sync import ensure_safe_parent

STATUS_DIR = Path('Spletna-ucilnica')
TEXT_MARKER = '# Generated by FE Moodle Sync; do not edit'


def last_successful(previous: dict, current: dict) -> str | None:
    if current.get('status') == 'ok':
        return current.get('finished_at')
    return previous.get('last_success_at') or (
        previous.get('finished_at') if previous.get('status') == 'ok' else None)


def safe_time(value: object) -> str:
    if not isinstance(value, str) or not value:
        return 'Še ni uspešne sinhronizacije'
    try:
        dt = datetime.fromisoformat(value.replace('Z', '+00:00'))
        if dt.tzinfo is None:
            return 'Neznan čas'
        return dt.astimezone(timezone.utc).strftime('%d. %m. %Y, %H:%M UTC')
    except ValueError:
        return 'Neznan čas'


def write_text(root: Path, path: Path, content: str) -> None:
    dest = ensure_safe_parent(root, path)
    if dest.exists():
        if not dest.is_file() or not dest.read_text('utf-8', errors='replace').startswith(TEXT_MARKER):
            raise ValueError(f'Refusing to overwrite user-owned status: {path}')
        if dest.read_text('utf-8') == content:
            return
    fd, tmp = tempfile.mkstemp(prefix='.fe-status-', dir=dest.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            os.fchmod(f.fileno(), 0o644)
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, dest)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def publish_status(root: Path, state_dir: Path, summary: dict) -> dict:
    """Keep last completed success while reporting failed or partial attempts."""
    previous = {}
    status_file = state_dir / 'status.json'
    if status_file.exists():
        try:
            loaded = json.loads(status_file.read_text(encoding='utf-8'))
            if isinstance(loaded, dict):
                previous = loaded
        except (ValueError, OSError):
            pass
    last = last_successful(previous, summary)
    summary['last_success_at'] = last
    state = str(summary.get('status', 'unknown'))
    if state not in ('ok', 'partial', 'failed'):
        state = 'unknown'
    state_name = {'ok':'Uspešno','partial':'Delno uspešno',
                  'failed':'Napaka','unknown':'Neznano'}[state]
    files = summary.get('files') or {}
    try:
        errors = max(0, int(files.get('errors', 0)))
    except (ValueError, TypeError):
        errors = 0
    reason = str(summary.get('error_type') or
                 (summary.get('navigation') or {}).get('error_type') or '')
    # Only an exception class name may be exported; never copy raw errors,
    # URLs, filesystem paths, session keys or credentials.
    reason = reason if reason.isidentifier() and len(reason) <= 60 else ''
    last_label, check_label = safe_time(last), safe_time(summary.get('finished_at'))
    # An inaccessible forum redirected to the same course is unsupported,
    # not a failed sync. Show it explicitly even when other work succeeded.
    try:
        forum_warnings = max(0,int(summary.get('announcements_returned_to_course',0)))
    except (ValueError,TypeError):
        forum_warnings = 0
    forum_notice = (f'Neprebrani forumi (preusmerjeni na predmet): {forum_warnings}\n'
                    if forum_warnings else '')
    forum_html_notice = (f'<p style="color:#926208">Opozorilo: {forum_warnings} forum(ov) '
                         'preusmerja na pregled predmeta in ni arhiviranih.</p>'
                         if forum_warnings else '')
    calendar=summary.get('calendar') or {}
    changes=summary.get('changes') or {}
    calendar_available=calendar.get('available') is True
    calendar_label=('Na voljo' if calendar_available else 'Ni preverjenih podatkov')
    try:
        recent_count=max(0,int(changes.get('recent',0)))
    except (ValueError,TypeError):
        recent_count=0
    pdf=summary.get('pdf_index') or {}
    def pdf_count(name):
        try:return max(0,int(pdf.get(name,0)))
        except (ValueError,TypeError):return 0
    pdf_total=pdf_count('total')
    pdf_ready=pdf_count('searchable')
    pdf_pending=pdf_count('pending')
    pdf_no_text=pdf_count('no_text')
    pdf_part=pdf_count('partial')
    pdf_notice=(f'Iskanje po besedilu PDF: {pdf_ready}/{pdf_total} datotek, '
                f'čaka {pdf_pending}, brez besedila {pdf_no_text}, delno {pdf_part}.'
                if 'total' in pdf else
                'Iskanje PDF: indeks še ni na voljo.')
    login_link_exists=(root/'Spletna-ucilnica/POVEZI.html').is_file()
    login_text=(('Za obnovitev prijave odpri Spletna-ucilnica/POVEZI.html.\n')
                if login_link_exists else
                'Na prenosniku obnovi sejo: bash ~/Downloads/obnovi-sejo.sh\n')
    txt = (f'{TEXT_MARKER}\n\nLOKALNA SPLETNA UČILNICA FE\n'
           f'Zadnja uspešna osvežitev: {last_label}\n'
           f'Zadnji poskus: {check_label}\n'
           f'Stanje zadnjega poskusa: {state_name}\n'
           f'Napake datotek: {errors}\n'
           f'Tip napake: {reason or "-"}\n'
           f'{forum_notice}'
           f'Koledar e.FE: {calendar_label}\n'
           f'Novosti zadnjih 30 dni: {recent_count}\n'
           f'{pdf_notice}\n\n'
           f'{login_text}'
           'Prijava prek UL SSO je ročna. Piškotki ostanejo zunaj mape FE.\n')
    colors = {'ok':'#156848','partial':'#926208','failed':'#b3261e',
              'unknown':'#555'}
    h = escape
    html = (f'<!doctype html><html lang="sl"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            '<meta http-equiv="Content-Security-Policy" '
            'content="default-src \x27none\x27; style-src \x27unsafe-inline\x27">'
            '<title>Stanje sinhronizacije · Lokalna e.FE</title>'
            '<style>body{font:15px/1.6 system-ui,Arial;margin:0;background:#f7f7f7;'
            'color:#292929}nav{background:#d92222;padding:12px 24px}'
            'nav a{color:white}main{max-width:720px;margin:24px auto;padding:24px;'
            'background:white;border:1px solid #ddd;border-radius:8px}'
            'h1{font-size:24px}.stamp{font-size:22px;font-weight:bold}'
            'code{background:#eee;padding:4px}a{color:#0965af}'
            '@media(max-width:760px){main{margin:10px;padding:16px}}</style></head>'
            f'<body>{MARKER}<nav><a href="index.html">← Moji predmeti</a></nav>'
            '<main><h1>Stanje lokalne spletne učilnice</h1>'
            '<p>Zadnja uspešna osvežitev</p>'
            f'<p class="stamp">{h(last_label)}</p>'
            f'<p>Zadnji poskus: <strong>{h(check_label)}</strong></p>'
            f'<p style="color:{colors[state]}"><strong>Stanje: {h(state_name)}</strong></p>'
            f'<p>Napake datotek: {errors}</p>'
            f'{forum_html_notice}'
            f'<p>Koledar e.FE: <strong>{h(calendar_label)}</strong></p>'
            f'<p>Novosti zadnjih 30 dni: <strong>{recent_count}</strong> '
            '<a href="NOVOSTI.html">Poglej novosti</a> · '
            '<a href="KOLEDAR.html">Poglej koledar</a></p>'
            f'<p>{h(pdf_notice)} <a href="ISKANJE.html">Iskanje vseh gradiv</a></p>'
            f'{f"<p>Vrsta napake: {h(reason)}</p>" if reason else ""}'
            '<hr><h2>Ko prijava poteče</h2>'
            + ('<p><a href="POVEZI.html">Odpri zasebno prijavo v e.FE →</a></p>'
               if login_link_exists else
               '<p>Na prenosniku zaženi <code>bash ~/Downloads/obnovi-sejo.sh</code>.</p>')
            + '<p>Geslo in prijavni piškotki niso shranjeni v mapi FE.</p>'
            '<p><a href="https://ucilnica-fe.uni-lj.si">Izvirna e.FE</a></p>'
            '</main></body></html>\n')
    write_generated(root, STATUS_DIR / 'STANJE.html', html)
    write_text(root, STATUS_DIR / 'STANJE.txt', txt)
    return {'last_success_at':last, 'status_file':'Spletna-ucilnica/STANJE.html'}
