def e(s) -> str:
    return escape(str(s), quote=True)


def local_href(current_dir: Path, target: Path) -> str:
    """Relative file URI usable when browsing synced FE folder offline."""
    relative = Path(os.path.relpath(target, current_dir)).as_posix()
    return quote(relative, safe='/')


