def module_url(module: dict) -> str:
    kind = str(module.get('type', ''))
    ident = module.get('id')
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,35}', kind) or type(ident) is not int or not 0 < ident < 2**31:
        return ''
    return f'{BASE}/mod/{kind}/view.php?id={ident}'


def course_url(course: dict) -> str:
    ident=course['id']
    if type(ident) is not int or not 0 < ident < 2**31:
        return BASE
    return f'{BASE}/course/view.php?id={ident}'


def file_kind(path: Path) -> str:
    ext = path.suffix.lower()
    if ext == '.pdf':return 'PDF'
    if ext in ('.doc','.docx','.odt'):return 'DOC'
    if ext in ('.ppt','.pptx','.odp'):return 'PPT'
    if ext in ('.zip','.7z','.rar'):return 'ZIP'
    if ext in ('.png','.jpg','.jpeg','.gif','.svg'):return 'IMG'
    return 'FILE'


def valid_stored_files(root: Path, records: list[dict], base: Path) -> list[Path]:
    """Never link outside the intended Moodle module or through symlinks."""
    result = []
    absolute_root = root.resolve(strict=True)
    for record in records:
        raw = record.get('rel_path', '')
        rel = Path(raw)
        if rel.is_absolute() or '..' in rel.parts or not rel.parts:
            continue
        try:
            rel.relative_to(base)
        except ValueError:
            continue
        path = root / rel
        if any(piece.is_symlink() for piece in (root.joinpath(*rel.parts[:i]) for i in range(1,len(rel.parts)+1))):
            continue
        if not path.is_file() or not path.resolve().is_relative_to(absolute_root):
            continue
        result.append(path)
    return sorted(set(result), key=lambda p:p.as_posix().casefold())


def html_module(module: dict, root: Path, course: dict, records: list[dict], index_dir: Path) -> tuple[str,int]:
    from .sync import course_dir,folder_dir
    kind=str(module['type'])
    title=str(module['title'])
    mid=module['id']
    url=module_url(module)
    title_label=re.sub(r'\s+Mapa$', '', title).strip() if kind=='folder' else title
    safe_title=e(title_label)
    badge='<span class="pill local">Lokalno gradivo</span>' if kind=='folder' else '<span class="pill web">Samo na e.FE</span>'
    inner=''
    count=0
    if kind=='folder':
        base=course_dir(course)/folder_dir(module)
        files=valid_stored_files(root,records,base)
        count=len(files)
        groups=defaultdict(list)
        for p in files:groups[p.relative_to(root/base).parent.as_posix()].append(p)
        if not files:
            inner='<p class="empty">V tej mapi trenutno ni lokalno prenesenih datotek.</p>'
        for folder,items in sorted(groups.items(),key=lambda x:(x[0]!='.',x[0].casefold())):
            if folder!='.':inner+=f'<div class="subfolder">📁 {e(folder)}</div>'
            inner+='<ul class="file-list">'
            for file in items:
                href=local_href(index_dir,file)
                label=file.name
                size=file.stat().st_size
                readable_size=(f'{size/1024/1024:.1f} MB' if size>=1024*1024 else f'{max(1, round(size/1024))} KB')
                inner+=(f'<li class="file-row" data-search="{e(title_label+" "+folder+" "+label)}">'
                        f'<a href="{e(href)}"><span class="file-icon">{file_kind(file)}</span>'
                        f'<span>{e(label)}</span><small>{e(readable_size)}</small></a></li>')
            inner+='</ul>'
    else:
        inner='<p class="folder-desc">Vsebina te dejavnosti še ni shranjena lokalno. Za ogled uporabi izvirno učilnico.</p>'
    online=(f'<a class="sub" href="{e(url)}" target="_blank" rel="noopener noreferrer">Odpri na e.FE ↗</a>' if url else '')
    block=(f'<section class="panel section" id="mod-{e(mid)}">'
           f'<div class="section-head"><h2>{safe_title}</h2>{badge}</div>'
           f'<p class="folder-desc">{e(str(count)+" lokalnih datotek") if kind=="folder" else e("Dejavnost: "+kind)} · {online}</p>'
           f'{inner}</section>')
    return block,count


def render_course(root:Path, course:dict, modules:list[dict], records:list[dict], main_index:Path, updated:str) -> tuple[str,int]:
    from .sync import course_dir
    index_dir=root/course_dir(course)
    home=local_href(index_dir,main_index)
    links=''.join(f'<a class="side-link" href="#mod-{m["id"]}">{e(re.sub(r"\\s+Mapa$","",str(m["title"])))}</a>' for m in modules)
    blocks=[];total=0
    for module in modules:
        fragment,count=html_module(module,root,course,records,index_dir)
        blocks.append(fragment);total+=count
    intro=(f'<div class="crumb"><a href="{e(home)}">Vsi predmeti</a> / {e(course["title"])}</div>'
           '<div class="intro"><div class="eyebrow">Arhiv predmeta</div>'
           f'<h1>{e(course["title"])}</h1><p class="sub">Moodle modulov: {len(modules)} · lokalnih datotek: {total}. '
           'Nekatere dejavnosti so dostopne samo na spletu.</p>'
           f'<div class="stats"><a class="btn" href="{e(course_url(course))}" target="_blank" rel="noopener noreferrer">Izvirni predmet ↗</a></div></div>')
    sidebar=f'<aside class="panel sidebar"><h2>Vsebina predmeta</h2><div class="sidebar-links">{links}</div></aside>'
    body=(intro+'<div class="layout">'+sidebar+'<main class="maincol">'
          '<div class="tools"><input class="search" type="search" oninput="filterItems(this)" '
          'placeholder="Poišči lokalno datoteko ..." aria-label="Poišči datoteko">'
          '<span class="sub">Prenesene datoteke odpreš neposredno.</span></div>'
          +''.join(blocks)+'</main></div>')
    return page(str(course['title']),body,updated),total


def render_home(root:Path,courses:list[dict],course_totals:dict[int,int],updated:str) -> str:
    from .sync import course_dir
    main=root/'Spletna-ucilnica'
    cards=[]
