        cards.append(f'<a class="course-card" data-search="{e(course["title"]+" "+course.get("shortname",""))}" href="{e(href)}">'
                     f'<span class="arrow">↗</span><span class="pill">PREDMET</span>'
                     f'<h3>{e(course["title"])}</h3><p class="sub">{e(course.get("shortname",""))}</p>'
                     f'<span class="pill local">{total} lokalnih datotek</span></a>')
