def module_url(module: dict) -> str:
    kind=str(module.get('type',''))
    ident=module.get('id')
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,35}',kind) or type(ident) is not int or not 0<ident<2**31:
        return ''
    return f'{BASE}/mod/{kind}/view.php?id={ident}'


def course_url(course:dict) -> str:
    ident=course['id']
    return f'{BASE}/course/view.php?id={ident}' if type(ident) is int and 0<ident<2**31 else BASE


def file_kind(path:Path) -> str:
    ext=path.suffix.lower()
    return ({'.pdf':'PDF','.doc':'DOC','.docx':'DOC','.ppt':'PPT','.pptx':'PPT','.zip':'ZIP','.png':'IMG','.jpg':'IMG','.jpeg':'IMG'}.get(ext,'FILE'))


def valid_stored_files(root:Path,records:list[dict],base:Path) -> list[Path]:
    result=[]
    absolute_root=root.resolve(strict=True)
    for record in records:
        raw=record.get('rel_path','')
        if not isinstance(raw,str) or not raw:continue
        rel=Path(raw)
        if rel.is_absolute() or '..' in rel.parts or not rel.parts:continue
        try:rel.relative_to(base)
        except ValueError:continue
        path=root/rel
        if any(piece.is_symlink() for piece in (root.joinpath(*rel.parts[:i]) for i in range(1,len(rel.parts)+1))):continue
        if not path.is_file() or not path.resolve().is_relative_to(absolute_root):continue
        result.append(path)
    return sorted(set(result),key=lambda p:p.as_posix().casefold())


def display_title(module:dict) -> str:
    label=str(module['title'])
    label=re.sub(r'\s+Mapa$','',label) if module['type']=='folder' else label
    label=re.sub(r'\s+(?:Forum|Stran|Naloga|Kviz)$','',label) if module['type'] in ('forum','page','assign','quiz') else label
    return label.strip() or str(module['title'])


def html_module(module:dict,root:Path,course:dict,records:list[dict],index_dir:Path) -> tuple[str,int]:
    from .sync import course_dir,folder_dir,resource_dir
    kind=str(module['type']);title=display_title(module);ident=module['id']
    online=module_url(module)
    icon_key=kind if kind in ICONS else 'file'
    icon=f'<span class="activity-symbol {e(icon_key)}">{ICONS[icon_key]}</span>'
    if kind=='resource':
        base=course_dir(course)/resource_dir(module)
        files=valid_stored_files(root,records,base)
        if len(files)==1:
            local_file=files[0]
            href=local_href(index_dir,local_file)
            return (f'<div class="activity" id="mod-{e(ident)}" data-activity data-availability="local" '
                    f'data-search="{e(title)} {e(local_file.name)}"><div class="activity-row">{icon}'
                    f'<div class="activity-text"><a class="activity-title" href="{e(href)}">{e(title)}</a>'
                    f'<div class="activity-sub">{e(local_file.name)}</div></div>'
                    '<span class="status local">lokalno</span></div></div>',1)
    # Local text snapshots of Moodle pages and announcement forums.
    # Always verify this is an owned generated file, not a user's notes.
    if kind in ('page','forum'):
        from .content import page_dir,forum_dir,is_announcement
        if kind=='page' or is_announcement(module):
            relative=(page_dir(module) if kind=='page' else forum_dir(module))
            local_path=root/course_dir(course)/relative/'index.html'
            if local_path.is_file() and not local_path.is_symlink():
                try:
                    owned=MARKER in local_path.read_text(encoding='utf-8',errors='replace')
                except OSError:
                    owned=False
                if owned:
                    href=local_href(index_dir,local_path)
                    label='lokalna stran' if kind=='page' else 'lokalna obvestila'
                    return (f'<div class="activity" id="mod-{e(ident)}" data-activity data-availability="local" '
                            f'data-search="{e(title)}"><div class="activity-row">{icon}'
                            f'<div class="activity-text"><a class="activity-title" href="{e(href)}">{e(title)}</a>'
                            f'<div class="activity-sub">{e(label)}</div></div>'
                            '<span class="status local">lokalno</span></div></div>',1)
    if kind!='folder':
        external=(f'<a class="activity-title" href="{e(online)}" target="_blank" rel="noopener noreferrer">{e(title)}</a>'
                  if online else f'<span class="activity-title">{e(title)}</span>')
        return (f'<div class="activity" id="mod-{e(ident)}" data-activity data-availability="web" '
                f'data-search="{e(title)}"><div class="activity-row">{icon}'
                f'<div class="activity-text">{external}</div>'
                '<span class="status remote" title="Vsebina ni prenesena">e.FE</span></div></div>',0)
    base=course_dir(course)/folder_dir(module)
    files=valid_stored_files(root,records,base)
    local=len(files)>0
    search=' '.join([title]+[str(p.relative_to(root/base)) for p in files])
    inner=[]
    previous_group=None
    for f in files:
        folder=f.relative_to(root/base).parent.as_posix()
        if folder!=previous_group:
            if previous_group is not None:inner.append('</ul></div>')
            label='Datoteke' if folder=='.' else folder
            inner.append(f'<div class="folder-group"><div class="folder-name">{e(label)}</div><ul class="filelist">')
            previous_group=folder
        size=f.stat().st_size
        readable=(f'{size/1048576:.1f} MB' if size>=1048576 else f'{max(1,round(size/1024))} KB')
        inner.append(f'<li><a href="{e(local_href(index_dir,f))}"><span class="file-kind">{file_kind(f)}</span>'
                     f'<span>{e(f.name)}</span><span class="file-size">{e(readable)}</span></a></li>')
    if previous_group is not None:inner.append('</ul></div>')
    if not files:inner.append('<p class="empty">Ni prenesenih datotek v tej mapi.</p>')
    detail=(f'<span class="folder-note">{len(files)} lokalnih datotek · '
            + (f'<a href="{e(online)}" target="_blank" rel="noopener noreferrer">Poglej izvirnik na e.FE ↗</a>' if online else ''))
    detail+='</span>'
    availability='local' if local else 'web'
    status='<span class="status local">lokalno</span>' if local else '<span class="status remote">e.FE</span>'
    return (f'<div class="activity" id="mod-{e(ident)}" data-activity data-availability="{availability}" data-search="{e(search)}">'
            f'<details class="folder-toggle"><summary class="activity-row">{icon}'
            f'<span class="activity-text"><span class="activity-title">{e(title)}</span></span>{status}'
            '<span class="expand-caret" aria-hidden="true">▸</span></summary>'
            f'<div class="folder-content">{detail}{"".join(inner)}</div></details></div>',len(files))


def group_modules(course:dict,modules:list[dict]) -> OrderedDict[str,list[dict]]:
    """Preserve Moodle headings; for known Mat I module IDs use screenshot fallback."""
    groups=OrderedDict()
    for m in modules:
        title=clean_section_title(str(m.get('section_title','')))
        if not title and course.get('id')==4149 and type(m.get('id')) is int:
            title=MAT1_SECTIONS.get(m['id'],'')
        if not title:title='Vsebina predmeta'
        groups.setdefault(title,[]).append(m)
    if course.get('id')==4149 and modules and not any(m.get('section_title') for m in modules):
        # The screenshot shows these two additional empty sections.
        groups={name:groups.pop(name,[]) for name in MAT1_ORDER} | groups
    return OrderedDict(groups)


def render_course(root:Path,course:dict,modules:list[dict],records:list[dict],main_index:Path,updated:str)->tuple[str,int]:
    from .sync import course_dir
    index_dir=root/course_dir(course)
    home=local_href(index_dir,main_index)
    sections=[];total=0
    groups=group_modules(course,modules)
    for i,(name,activities) in enumerate(groups.items()):
        blocks=[]
        for module in activities:
            piece,count=html_module(module,root,course,records,index_dir)
            blocks.append(piece);total+=count
        contents=''.join(blocks) if blocks else '<p class="activity-empty">V tem razdelku trenutno ni objavljenih dejavnosti.</p>'
        sections.append(f'<details class="section" data-section open id="section-{i}"><summary class="section-summary">'
                        f'<span class="chevron" aria-hidden="true">⌄</span><span>{e(name)}</span></summary>'
                        f'<div class="activities">{contents}</div></details>')
    body=(f'<div class="breadcrumb"><a href="{e(home)}">Moji predmeti</a> / {e(course["title"])}</div>'
          f'<div class="page-title"><h1>{e(course["title"])}</h1>'
          f'<a class="original" href="{e(course_url(course))}" target="_blank" rel="noopener noreferrer">Odpri izvirni predmet ↗</a></div>'
          '<main class="course-shell" id="content"><div class="filterbar">'
          '<input id="filterSearch" type="search" oninput="filterItems()" placeholder="Poišči gradivo ..." aria-label="Iskanje dejavnosti in datotek">'
          '<select id="filterType" aria-label="Filtriraj vsebino" onchange="filterItems()">'
          '<option value="all">Vsa vsebina</option><option value="local">Samo lokalno</option>'
          '<option value="web">Samo e.FE</option></select>'
          f'<span class="filter-note">{len(modules)} dejavnosti · {total} lokalnih datotek</span></div>'
          + ''.join(sections) + '<div id="noResults" class="no-results">Ni zadetkov za izbrane filtre.</div></main>')
    return page(str(course['title']),body,updated,home=home,subject=True,
                status_href=local_href(index_dir,root/'Spletna-ucilnica/STANJE.html'),
                updates_href=local_href(index_dir,root/'Spletna-ucilnica/NOVOSTI.html'),
                calendar_href=local_href(index_dir,root/'Spletna-ucilnica/KOLEDAR.html'),
                search_href=local_href(index_dir,root/'Spletna-ucilnica/ISKANJE.html'),
                login_href=(local_href(index_dir,root/'Spletna-ucilnica/POVEZI.html')
                            if (root/'Spletna-ucilnica/POVEZI.html').is_file() else '')),total


