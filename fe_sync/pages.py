           '<h1>Moja spletna učilnica</h1><p class="sub">Vsa prenesena gradiva na enem mestu. '
           'Odpri predmet, nato njegovo gradivo — deluje tudi brez povezave.</p></section>'
           f'<div class="stats"><div class="stat"><strong>{len(courses)}</strong><small>predmetov</small></div>'
