def write_generated(root:Path,relative:Path,body:str)->None:
    from .sync import ensure_safe_parent
    dest=ensure_safe_parent(root,relative)
    if dest.exists():
        if not dest.is_file():
            raise ValueError(f'Refusing to replace user-owned HTML: {relative}')
        # The generated marker is in the BODY, after a large inline CSS block.
        # Checking only the first 1800 characters incorrectly rejects beta1.1
        # and beta1.2 pages on the second sync. Read once, verify ownership,
        # and retain the existing protection against overwriting user HTML.
        existing = dest.read_text('utf-8',errors='replace')
        if MARKER not in existing:
            raise ValueError(f'Refusing to replace user-owned HTML: {relative}')
        if existing == body:
            return
    fd,tmp=tempfile.mkstemp(prefix='.fe-page-',dir=dest.parent)
    try:
        with os.fdopen(fd,'w',encoding='utf-8') as out:
            os.fchmod(out.fileno(),0o644)
            out.write(body);out.flush();os.fsync(out.fileno())
        os.replace(tmp,dest)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)


def build_site(root:Path,courses:list[dict],module_lists:dict[int,list[dict]],
               records:list[dict],updated:str,pdf_terms:dict[str,str]|None=None)->dict:
    from .sync import course_dir
    main=root/'Spletna-ucilnica/index.html'
    totals={}
    for course in courses:
        try:
            html,total=render_course(root,course,module_lists[course['id']],records,main,updated)
            write_generated(root,course_dir(course)/'index.html',html)
        except (ValueError, OSError) as exc:
            raise ValueError(f'course {course["id"]} navigation: {str(exc)[:160]}') from exc
        totals[course['id']]=total
    write_generated(root,Path('Spletna-ucilnica/index.html'),render_home(root,courses,totals,updated))
    from .search import render_search
    search=render_search(root,courses,module_lists,records,updated,pdf_terms=pdf_terms)
    return {'pages':len(courses)+1,'local_files_linked':sum(totals.values()),
            'home':'Spletna-ucilnica/index.html','search':search}
