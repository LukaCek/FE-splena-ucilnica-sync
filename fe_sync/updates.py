"""Local change history for verified Moodle files and generated course notes.

Only differences created during a sync run are recorded. No guessed changes,
no user-owned files, and no need to rescan all private FE notes.
"""
from __future__ import annotations

from datetime import datetime, timezone, timedelta
import hashlib
from pathlib import Path
import sqlite3

TEXT_MARKER='# Generated by FE Moodle Sync; do not edit'
MAX_EVENTS_PER_RUN=2000
MAX_HISTORY=300
WINDOW_DAYS=30


def _managed_notes(root:Path,courses:list[dict],module_lists:dict|None=None)->dict[str,dict]:
    from .sync import course_dir
    from .content import page_dir,forum_dir,is_announcement
    result={}
    for course in courses:
        folder=root/course_dir(course)
        modules=(module_lists or {}).get(course['id'])
        if modules is None:
            manifest=folder/'predmet.json'
            if not manifest.is_file() or manifest.is_symlink():
                continue
            try:
                import json
                info=json.loads(manifest.read_text(encoding='utf-8'))
                if info.get('id')!=course['id'] or not isinstance(info.get('modules'),list):
                    continue
                modules=info['modules']
            except (ValueError,OSError,TypeError):
                continue
        for module in modules:
            if not isinstance(module,dict) or type(module.get('id')) is not int:
                continue
            typ=module.get('type')
            try:
                if typ=='page':
                    candidates=[folder/page_dir(module)/'vsebina.md']
                elif is_announcement(module):
                    directory=folder/forum_dir(module)
                    if directory.is_symlink() or not directory.is_dir():
                        continue
                    candidates=list(directory.glob('tema-*.md'))[:150]
                else:continue
            except ValueError:
                continue
            for file in candidates:
                if file.is_symlink() or not file.is_file() or not file.resolve().is_relative_to(root):
                    continue
                try:
                    with file.open('rb') as handle:
                        head=handle.read(110)
                        if not head.startswith(TEXT_MARKER.encode('utf-8')):
                            continue
                        handle.seek(0)
                        digest=hashlib.file_digest(handle,'sha256').hexdigest()
                except OSError:
                    continue
                rel=file.relative_to(root).as_posix()
                result['note:'+rel]={'sha':digest,'rel':rel,'course_id':course['id'],
                    'course':course['title'],'label':str(module.get('title',''))[:160]}
    return result


def _stored_files(state,courses:list[dict])->dict[str,dict]:
    from .sync import course_dir
    folders=[(course_dir(c).as_posix()+'/',c) for c in courses]
    out={}
    for record in state.list_files():
        rel=record.get('rel_path')
        if not isinstance(rel,str):continue
        course=next((c for prefix,c in folders if rel.startswith(prefix)),None)
        if course is None:continue
        if Path(rel).is_absolute() or '..' in Path(rel).parts:continue
        out['file:'+record['remote_key']]={'sha':record['sha256'],'rel':rel,
             'course_id':course['id'],'course':course['title'],
             'label':Path(rel).name[:160]}
    return out


def capture(root:Path,state,courses:list[dict],modules:dict|None=None)->dict[str,dict]:
    return _stored_files(state,courses)|_managed_notes(root,courses,modules)


def ensure_history(state):
    state.c.execute('''CREATE TABLE IF NOT EXISTS activity_changes(
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        seen_at TEXT NOT NULL, kind TEXT NOT NULL,
        course_id INTEGER NOT NULL, course TEXT NOT NULL,
        label TEXT NOT NULL, rel_path TEXT NOT NULL
    )''')
    state.c.commit()


def record_changes(state,before:dict,after:dict,now:str)->dict:
    ensure_history(state)
    new=0
    updated=0
    entries=[]
    for key,entry in after.items():
        previous=before.get(key)
        if previous is not None and previous['sha']==entry['sha']:continue
        # Local file edits are never included; binary entries come exclusively
        # from SQLite's successful verified file downloads.
        kind='novo' if previous is None else 'posodobljeno'
        entries.append((now,kind,entry['course_id'],entry['course'][:180],
                        entry['label'][:180],entry['rel']))
        new+=kind=='novo'
        updated+=kind=='posodobljeno'
        if len(entries)>=MAX_EVENTS_PER_RUN:break
    with state.c:
        state.c.executemany('''INSERT INTO activity_changes(
            seen_at,kind,course_id,course,label,rel_path)
            VALUES(?,?,?,?,?,?)''',entries)
        cutoff=(datetime.fromisoformat(now)-timedelta(days=WINDOW_DAYS)).isoformat()
        state.c.execute('DELETE FROM activity_changes WHERE seen_at<?',(cutoff,))
        state.c.execute('''DELETE FROM activity_changes WHERE id NOT IN
             (SELECT id FROM activity_changes ORDER BY id DESC LIMIT ?)''',(MAX_HISTORY,))
    return {'new':new,'updated':updated,'recent':state.c.execute(
        'SELECT COUNT(*) FROM activity_changes').fetchone()[0]}


def history(state)->list[dict]:
    ensure_history(state)
    rows=state.c.execute('''SELECT seen_at,kind,course_id,course,label,rel_path
                         FROM activity_changes ORDER BY id DESC LIMIT ?''',
                         (MAX_HISTORY,)).fetchall()
    return [dict(row) for row in rows]


def render_history(root:Path,entries:list[dict])->dict:
    from .pages import page,e,local_href,write_generated
    from .status import write_text
    main=root/'Spletna-ucilnica'
    lines=[]
    plain=[TEXT_MARKER,'','NOVOSTI LOKALNE e.FE','Zadnjih 30 dni.']
    for entry in entries:
        rel=Path(entry['rel_path'])
        if rel.is_absolute() or '..' in rel.parts:
            continue
        target=root/rel
        if target.is_symlink() or not target.is_file() or not target.resolve().is_relative_to(root):
            continue
        seen=entry['seen_at'][:16].replace('T',' ')
        desc=f'{entry["kind"]}: {entry["course"]} — {entry["label"]}'
        lines.append(f'<li><small>{e(seen)} UTC</small> · {e(entry["kind"])} · '
                     f'<strong>{e(entry["course"])}</strong> — '
                     f'<a href="{e(local_href(main,target))}">{e(entry["label"])}</a></li>')
        plain.append(f'{seen} UTC — {desc}')
    body=('<div class="breadcrumb"><a href="index.html">Moji predmeti</a> / Novosti</div>'
          '<main class="course-shell" id="content"><h1>Novosti v gradivih</h1>'
          '<p class="muted-info">Nove ali spremenjene datoteke in besedila, ki jih je zaznala '
          'lokalna sinhronizacija v zadnjih 30 dneh. To ni seznam vseh sprememb na e.FE.</p>'
          +(f'<ul class="changes-list">{"".join(lines)}</ul>' if lines else
            '<p>V zadnjih 30 dneh ni zaznanih novih ali spremenjenih gradiv.</p>')
          +'</main>')
    now=datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')
    write_generated(root,Path('Spletna-ucilnica/NOVOSTI.html'),
                   page('Novosti',body,now,home='index.html',status_href='STANJE.html'))
    write_text(root,Path('Spletna-ucilnica/NOVOSTI.txt'),'\n'.join(plain)+'\n')
    return {'shown':len(lines)}
